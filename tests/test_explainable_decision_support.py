"""
tests/test_explainable_decision_support.py
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
Unit and operational integration test suite for Phase 25: Explainable Decision Support.

Validates:
1. All 8 required explainability facets on every recommendation:
   - Recommendation text
   - Recommendation category (6 canonical categories)
   - Supporting evidence (conflicts, resources, services, bottlenecks)
   - Delay analysis (direct, propagated, total savings)
   - Counterfactual analysis (unmitigated delay, rejection impact, ripple risk)
   - Confidence / support metrics (constraint count, solver agreement, severity basis)
   - Constraint explanation (headway, platform, route, junction)
   - Ranking explanation
   - 5-step controller reasoning path
2. Contextual separation between LIVE_OPERATIONAL and HYPOTHETICAL_SCENARIO.
3. Deterministic repeatability across repeated scenario runs.
4. FastAPI POST /api/v1/what-if endpoint exposure and validation.
"""

import pytest
from fastapi.testclient import TestClient

from backend.app.main import app
from decision_support import (
    DecisionSupportAdvisor,
    OperationalSeverity,
    OperationalSituation,
    PriorityTier,
    Recommendation,
    RecommendationCategory,
    RecommendationType,
)
from optimization.scenarios import Scenario
from simulation.network import Network
from simulation.state import SimulationState

client = TestClient(app)

CANONICAL_CATEGORIES = {
    "precedence change",
    "holding",
    "platform reassignment",
    "dispatch sequencing",
    "speed management",
    "maintain schedule",
}


@pytest.fixture(scope="module")
def advisor() -> DecisionSupportAdvisor:
    return DecisionSupportAdvisor()


class TestExplainableDecisionSupportCore:
    """Verify all 8 explainability facets on recommendations generated by DecisionSupportAdvisor."""

    def test_maintain_schedule_explainability(self, advisor: DecisionSupportAdvisor):
        """Verify normal state produces 'maintain schedule' with all 8 explainability facets."""
        state = SimulationState()
        state.initialize_from_network(advisor.network)
        situation = advisor.assess_current_state(state)

        recs = advisor.generate_recommendations(situation, operational_context="LIVE_OPERATIONAL")
        assert len(recs) >= 1
        rec = recs[0]

        # 1. Recommendation text
        assert rec.title != ""
        assert rec.reason != ""
        assert "Maintain Current Published Timetable" in rec.title

        # 2. Recommendation category
        assert rec.category == "maintain schedule"
        assert rec.category in CANONICAL_CATEGORIES

        # 3. Supporting evidence
        assert rec.supporting_evidence is not None
        assert len(rec.supporting_evidence.triggering_conflicts) > 0
        assert isinstance(rec.supporting_evidence.contested_resources, list)
        assert isinstance(rec.supporting_evidence.affected_services, list)
        assert isinstance(rec.supporting_evidence.bottlenecks, list)

        # 4. Delay analysis
        assert rec.delay_analysis is not None
        assert rec.delay_analysis.total_savings_minutes == 0.0
        assert rec.delay_analysis.direct_delay_reduction_minutes == 0.0
        assert rec.delay_analysis.propagated_delay_reduction_minutes == 0.0

        # 5. Counterfactual analysis
        assert rec.counterfactual_analysis is not None
        assert rec.counterfactual_analysis.impact_if_not_applied != ""
        assert rec.counterfactual_analysis.downstream_ripple_risk != ""

        # 6. Confidence / support metrics
        assert rec.confidence_metrics is not None
        assert rec.confidence_metrics.supporting_constraints_count >= 1
        assert rec.confidence_metrics.optimization_agreement >= 0.9
        assert rec.confidence_metrics.conflict_severity_basis == rec.priority_tier.value

        # 7. Constraint explanation (all 4 dimensions)
        assert rec.constraint_explanation is not None
        assert "headway" in rec.constraint_explanation.headway.lower()
        assert "platform" in rec.constraint_explanation.platform_capacity.lower()
        assert "block" in rec.constraint_explanation.route_occupancy.lower()
        assert "interlocking" in rec.constraint_explanation.junction_contention.lower()

        # 8. Recommendation ranking explanation
        assert rec.ranking_explanation != ""
        assert "Ranked #1" in rec.ranking_explanation

        # 9. Reasoning path (5 chronological steps)
        assert len(rec.reasoning_path) == 5
        phases = [step.phase for step in rec.reasoning_path]
        assert phases == ["TRIGGER", "BOTTLENECK", "CONSTRAINTS", "DECISION", "OUTCOME"]

        # Context
        assert rec.operational_context == "LIVE_OPERATIONAL"

    def test_disruption_scenario_produces_actionable_explanations(self, advisor: DecisionSupportAdvisor):
        """Verify What-If scenario produces actionable explainable directives."""
        scenario = Scenario(
            scenario_id="SCEN_EXP_TEST",
            name="Explainability Test Disruption",
            description="Testing 25 min late departure of 12607 Express at MAS.",
            departure_delays={"SRV_12607_01": 25.0},
        )
        services = ["SRV_12607_01", "SRV_12609_01", "SRV_12610_01", "SRV_43411_01"]

        assessment = advisor.evaluate_what_if_scenario(scenario, service_ids=services)
        assert len(assessment.recommendations) > 0

        for rec in assessment.recommendations:
            # 1. Text
            assert len(rec.title) > 0
            assert len(rec.reason) > 0

            # 2. Category
            assert rec.category in CANONICAL_CATEGORIES

            # 3. Evidence
            assert rec.supporting_evidence is not None
            assert len(rec.supporting_evidence.bottlenecks) > 0

            # 4. Delay Analysis
            assert rec.delay_analysis is not None
            assert rec.delay_analysis.total_savings_minutes >= 0.0
            expected_sum = round(
                rec.delay_analysis.direct_delay_reduction_minutes
                + rec.delay_analysis.propagated_delay_reduction_minutes,
                1,
            )
            assert abs(expected_sum - round(rec.delay_analysis.total_savings_minutes, 1)) <= 0.1

            # 5. Counterfactual Analysis
            assert rec.counterfactual_analysis is not None
            assert rec.counterfactual_analysis.unmitigated_delay_minutes >= 0.0
            assert len(rec.counterfactual_analysis.impact_if_not_applied) > 10
            assert len(rec.counterfactual_analysis.downstream_ripple_risk) > 5

            # 6. Confidence Metrics
            assert rec.confidence_metrics is not None
            assert rec.confidence_metrics.supporting_constraints_count >= 2
            assert rec.confidence_metrics.optimization_agreement >= 0.9

            # 7. Constraint Explanation
            assert len(rec.constraint_explanation.headway) > 0
            assert len(rec.constraint_explanation.platform_capacity) > 0
            assert len(rec.constraint_explanation.route_occupancy) > 0
            assert len(rec.constraint_explanation.junction_contention) > 0

            # 8. Ranking Explanation
            assert rec.ranking_explanation.startswith("Ranked #")

            # 9. Reasoning path
            assert len(rec.reasoning_path) == 5

            # Operational context check
            assert rec.operational_context == "HYPOTHETICAL_SCENARIO"

    def test_speed_restriction_caution_order_category(self, advisor: DecisionSupportAdvisor):
        """Verify speed restriction scenario generates 'speed management' recommendation."""
        scenario = Scenario(
            scenario_id="SCEN_TSR_EXP",
            name="Speed Restriction Evaluation",
            description="TSR on MAS BBQ throat.",
            affected_service_ids=["SRV_12607_01", "SRV_12609_01"],
            track_speed_restrictions={"MAS_BBQ_THROAT_SEGMENT_DOWN": 10.0},
        )
        assessment = advisor.evaluate_what_if_scenario(
            scenario, service_ids=["SRV_12607_01", "SRV_12609_01"]
        )

        categories = {r.category for r in assessment.recommendations}
        assert "speed management" in categories
        tsr_rec = next(r for r in assessment.recommendations if r.category == "speed management")
        assert tsr_rec.recommendation_type == RecommendationType.SPEED_RESTRICTION_ADJUSTMENT
        assert "caution" in tsr_rec.reason.lower()
        assert tsr_rec.supporting_evidence is not None
        assert "MAS_BBQ_THROAT_SEGMENT_DOWN" in tsr_rec.affected_resources

    def test_serialization_to_dict_includes_all_explainability_fields(
        self, advisor: DecisionSupportAdvisor
    ):
        """Verify to_dict() returns clean JSON-serializable dictionaries with all 8 facets."""
        scenario = Scenario(
            scenario_id="SCEN_DICT_TEST",
            name="Dict Serialization",
            departure_delays={"SRV_12607_01": 20.0, "SRV_12609_01": 15.0},
        )
        assessment = advisor.evaluate_what_if_scenario(
            scenario, service_ids=["SRV_12607_01", "SRV_12609_01", "SRV_12610_01"]
        )

        d = assessment.to_dict()
        assert "recommendations" in d
        assert len(d["recommendations"]) > 0

        first_rec = d["recommendations"][0]
        required_keys = [
            "recommendation_id",
            "recommendation_type",
            "category",
            "title",
            "reason",
            "affected_services",
            "affected_resources",
            "baseline_delay_minutes",
            "expected_delay_minutes",
            "expected_delay_savings",
            "confidence_score",
            "priority_tier",
            "evidence_basis",
            "is_actionable",
            "operational_context",
            "supporting_evidence",
            "delay_analysis",
            "counterfactual_analysis",
            "confidence_metrics",
            "constraint_explanation",
            "ranking_explanation",
            "reasoning_path",
        ]
        for key in required_keys:
            assert key in first_rec, f"Missing key {key} in recommendation dict"

        # Check nested structures
        assert "triggering_conflicts" in first_rec["supporting_evidence"]
        assert "direct_delay_reduction_minutes" in first_rec["delay_analysis"]
        assert "impact_if_not_applied" in first_rec["counterfactual_analysis"]
        assert "supporting_constraints_count" in first_rec["confidence_metrics"]
        assert "headway" in first_rec["constraint_explanation"]
        assert len(first_rec["reasoning_path"]) == 5


class TestFastApiExplainableDirectives:
    """Verify POST /api/v1/what-if returns fully formed explainable recommendations."""

    def test_post_what_if_returns_explainability_fields(self):
        payload = {
            "scenario_id": "SCEN_API_EXPLAIN_TEST",
            "scenario_name": "API Explainability Test",
            "service_ids": ["SRV_12607_01", "SRV_12609_01", "SRV_12610_01"],
            "departure_delays": {"SRV_12607_01": 25.0},
        }
        res = client.post("/api/v1/what-if", json=payload)
        assert res.status_code == 200
        data = res.json()

        assert "recommendations" in data
        assert len(data["recommendations"]) > 0

        for r in data["recommendations"]:
            assert r["category"] in CANONICAL_CATEGORIES
            assert r["operational_context"] == "HYPOTHETICAL_SCENARIO"
            assert r["supporting_evidence"] is not None
            assert r["delay_analysis"] is not None
            assert r["counterfactual_analysis"] is not None
            assert r["confidence_metrics"] is not None
            assert r["constraint_explanation"] is not None
            assert r["ranking_explanation"] != ""
            assert len(r["reasoning_path"]) == 5
